    out += `    val ${name}${dark ? 'Dark' : 'Light'}: ColorScheme = ${dark ? 'dark' : 'light'}ColorScheme(\n`;
    out += roles.map(r => `        ${r} = Color(${hex(M[r].getArgb(s))})`).join(',\n');
